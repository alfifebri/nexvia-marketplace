const img = (id: string, width = 1200) =>
  `https://images.unsplash.com/${id}?auto=format&fit=crop&w=${width}&q=80`;

const colorGroup = (name: string, pairs: [string, string, number?][]): VariantGroup => ({
  name,
  options: pairs.map(([label, swatch, stock]) => ({
    label,
    value: label.toLowerCase().replace(/\s+/g, "-"),
    swatch,
    stock,
  })),
});

const sizeGroup = (name: string, sizes: string[], stockScale = 8): VariantGroup => ({
  name,
  options: sizes.map((size, index) => ({
    label: size,
    value: size.toLowerCase(),
    stock: Math.max(0, stockScale - index),
  })),
});

interface ProductSeed {
  id: string;
  slug: string;
  title: string;
  subtitle: string;
  description: string;
  highlights: string[];
  price: number;
  compareAtPrice?: number;
  currency?: Currency;
  category: string;
  brand: string;
  images: string[];
  rating: { rate: number; count: number };
  stock: number;
  sku: string;
  tags: string[];
  attributes: Record<string, string | number>;
  variants?: VariantGroup[];
  warrantyInformation?: string;
  shippingInformation?: string;
  returnPolicy?: string;
  vendorId: string;
  storeId: string;
  status?: Product["status"];
  isFeatured?: boolean;
  soldCount: number;
  createdAt: string;
}

const storeName = (storeId: string) => demoStores.find((store) => store.id === storeId)?.name ?? "Nexvia";

const makeProduct = (seed: ProductSeed): Product => {
  const compareAt = seed.compareAtPrice;
  return {
    ...seed,
    variants: seed.variants ?? [],
    currency: seed.currency ?? "USD",
    categoryLabel: categoryLabel(seed.category),
    thumbnail: seed.images[0],
    discountPercentage:
      compareAt && compareAt > seed.price ? Math.round(((compareAt - seed.price) / compareAt) * 100) : 0,
    storeName: storeName(seed.storeId),
    status: seed.status ?? "active",
    isFeatured: seed.isFeatured ?? false,
    source: "manual",
    warrantyInformation: seed.warrantyInformation ?? "2-year Nexvia-backed warranty.",
    shippingInformation: seed.shippingInformation ?? "Ships within 1–2 business days.",
    returnPolicy: seed.returnPolicy ?? "30-day free returns.",
  };
};

