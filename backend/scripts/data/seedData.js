export const categoryRoutes = [
  { vendorIndex: 0, patterns: [/audio/, /electronic/, /speaker/, /headphone/] },
  { vendorIndex: 1, patterns: [/laptop/, /smartphone/, /tablet/, /mobile/, /vehicle/, /motorcycle/, /gaming/] },
  { vendorIndex: 2, patterns: [/clothing/, /mens/, /womens/, /tops/, /shoe/, /watch/, /jewel/, /bag/, /sunglass/, /fashion/] },
  { vendorIndex: 3, patterns: [/furniture/, /home/, /kitchen/, /decor/] },
  { vendorIndex: 4, patterns: [/beauty/, /fragrance/, /skin/, /grocer/, /sport/, /outdoor/] },
];

export const resolveVendorIndex = (category = '') => {
  const normalized = String(category).toLowerCase();

  const route = categoryRoutes.find(({ patterns }) => patterns.some((pattern) => pattern.test(normalized)));
  if (route) return route.vendorIndex;

  const hash = [...normalized].reduce((total, character) => total + character.charCodeAt(0), 0);
  return hash % vendorBlueprints.length;
};
